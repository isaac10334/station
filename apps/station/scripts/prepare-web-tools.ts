import { readFile, readdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { createRequire } from "node:module";
import { resolvedPackageRoot } from "../../../tooling/package-resolution";
const require = createRequire(import.meta.url);
const packageRoot = (id: string) => dirname(require.resolve(`${id}/package.json`));

/** Embed only compiler, curated dependency source and declarations; never user config. */
const resources: Record<string, string> = {};
async function collect(
  root: string,
  prefix: string,
  accept: (path: string) => boolean,
) {
  for (const item of await readdir(root, { withFileTypes: true })) {
    const path = join(root, item.name),
      key = `${prefix}/${item.name}`;
    if (item.isDirectory()) await collect(path, key, accept);
    else if (accept(key)) resources[key] = await readFile(path, "utf8");
  }
}
for (const dependency of [
  "react",
  "react-dom",
  "scheduler",
  "@types/react",
  "@types/react-dom",
  "csstype",
])
  await collect(
    packageRoot(dependency),
    `node_modules/${dependency}`,
    (path) => /\.(js|json|ts)$/.test(path),
  );
await collect(join(packageRoot("typescript"), "lib"), "lib", (path) =>
  path.endsWith(".d.ts"),
);
// Read the installed public package artifacts, never another workspace's private source.
const sdkRoot = dirname(Bun.resolveSync("@station/sdk", import.meta.dir));
resources["node_modules/@station/sdk/index.js"] = await readFile(join(sdkRoot, "index.js"), "utf8");
resources["node_modules/@station/sdk/index.d.ts"] = await readFile(join(sdkRoot, "index.d.ts"), "utf8");
const contractsRoot = dirname(Bun.resolveSync("@station/capabilities/guest", import.meta.dir));
resources["node_modules/@station/capabilities/guest.d.ts"] = await readFile(join(contractsRoot, "guest.d.ts"), "utf8");
await collect(join(import.meta.dir,"../../../packages/ui/dist"), "node_modules/@station/ui", path => /\.(js|ts)$/.test(path));
resources["node_modules/@station/capabilities/icon-names.d.ts"] = await readFile(join(contractsRoot,"icon-names.d.ts"),"utf8");
async function worker(path: string) {
  const result = await Bun.build({
    entrypoints: [path],
    target: "browser",
    minify: true,
  });
  if (!result.success) throw new Error(String(result.logs));
  return result.outputs[0]!.text();
}
const compiler = await worker("src/services/web-build-worker.ts"),
  language = await worker("src/services/typescript-worker.ts");
await Bun.write(
  "src/generated/web-tools.ts",
  `// Generated by prepare-web-tools.ts.\nexport const resources = ${JSON.stringify(resources)};\nexport const buildWorker = ${JSON.stringify(compiler)};\nexport const languageWorker = ${JSON.stringify(language)};\nexport const wasm = ${JSON.stringify(Buffer.from(new Uint8Array(await readFile(join(packageRoot("esbuild-wasm"), "esbuild.wasm")))).toString("base64"))};\n`,
);

await Bun.write("src/generated/script-tools.ts", `// Generated fixed worker; never authored source.\nexport const scriptWorker = ${JSON.stringify(await worker("src/services/script-worker.ts"))};\n`);

await Bun.write("src/generated/program-tools.ts", `// Generated fixed workers and curated SDK; no authored source.\nexport const runtimeWorker = ${JSON.stringify(await worker("src/providers/scripting/worker-entry.ts"))};\nexport const compilerWorker = ${JSON.stringify(await worker("src/services/program-build-worker.ts"))};\n`);
for (const name of ["ui", "scripting", "capabilities"]) {
  const id = `@loop-kit/${name}`;
  await collect(join(resolvedPackageRoot(id, import.meta.dir), "dist"), `node_modules/${id}`, path => /\.(js|ts)$/.test(path));
}
await Bun.write("src/generated/program-resources.ts", `// Generated public SDK module sources.\nexport const resources = ${JSON.stringify(Object.fromEntries(Object.entries(resources).filter(([path]) => path.startsWith("node_modules/@loop-kit/"))))};\n`);

await Bun.write("src/generated/svg-edit-tools.ts", `// Generated pinned SVG-Edit engine for an opaque canvas frame.\nexport const svgEditFrame = ${JSON.stringify(await worker("src/ui/svg-edit-frame.ts"))};\n`);
