import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { Icon } from "@station/ui";
import { ICON_NAMES } from "@station/capabilities/icons";

// Deterministic source projection of the public icon catalog, with no override
// subscriptions, DOM parsing, user data or runtime dependency in the domain.
const sources = Object.fromEntries(ICON_NAMES.map(name => [name,
  renderToStaticMarkup(createElement(Icon, { name, builtIn: true }))
    .replace(/ (?:aria-hidden|focusable)="[^"]*"/g, "")
    .replace("<svg ", '<svg xmlns="http://www.w3.org/2000/svg" '),
]));
await Bun.write(new URL("../src/core/builtin-icon-sources.ts", import.meta.url), `// Generated by scripts/generate-builtin-icons.ts from @station/ui.\nexport const builtinIconSources: Readonly<Record<string, string>> = ${JSON.stringify(sources, null, 2)};\n`);
